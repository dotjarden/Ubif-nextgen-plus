const { test } = require('node:test');
const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
const fs = require('node:fs');
test('employee label and template value follow the profile, override and live settings', async t => {
  const dom = new JSDOM('<header><button aria-label="Profile">Icon</button></header>', { url: 'https://portal.ubreakifix.net', runScripts: 'outside-only' });
  t.after(() => dom.window.close());
  const w = dom.window;
  let apply;
  w.UBIFPlusSettings = { subscribe: fn => { apply = fn; }, get: async () => ({ employeeName: true, employeeFirstName: 'Jordan' }) };
  w.eval(fs.readFileSync(`${__dirname}/../extension/employee.js`, 'utf8'));
  await new Promise(resolve => w.setTimeout(resolve, 20));
  assert.equal(w.UBIFPlusEmployee.firstName, 'Jordan');
  const button = w.document.querySelector('button');
  assert.equal(w.document.querySelector('[data-ubif-employee-name]').parentElement, button);
  assert.equal(button.hasAttribute('data-ubif-profile-name'), true);
  let opens = 0;
  button.addEventListener('click', () => opens++);
  w.document.querySelector('[data-ubif-employee-name]').click();
  assert.equal(opens, 1, 'the name uses the original account-menu button');
  apply({ employeeName: false, employeeFirstName: 'Sam' });
  assert.equal(w.document.querySelector('[data-ubif-employee-name]'), null);
  assert.equal(w.UBIFPlusEmployee.firstName, 'Sam');
  assert.equal(button.hasAttribute('data-ubif-profile-name'), false);
  assert.equal(button.textContent, 'Icon');
  w.dispatchEvent(new w.MessageEvent('message', { source: w, data: { source: 'ubif-plus', type: 'employee-context', firstName: 'Alex' } }));
  apply({ employeeName: true, employeeFirstName: '' });
  assert.equal(w.UBIFPlusEmployee.firstName, 'Alex');
  assert.equal(w.document.querySelector('[data-ubif-employee-name]').textContent, 'Alex');
});

test('the native Portal avatar receives the signed-in store profile name and follows user switches', async t => {
  const dom = new JSDOM('<header class="components-header"><div class="components-header-opts"><button class="components-header-opts-avatar"><span class="avatar">JS</span></button></div></header>', { url: 'https://portal.ubreakifix.net', runScripts: 'outside-only' });
  t.after(() => dom.window.close());
  const w = dom.window;
  let listener;
  w.postMessage = data => w.queueMicrotask(() => w.dispatchEvent(new w.MessageEvent('message', { source: w, data })));
  const state = { auth: { user: { givenName: 'Jordan', familyName: 'Smith' } } };
  w.System = { resolve: id => id, get: () => ({ store: {getState: () => state, subscribe: fn => { listener = fn; }}, selectUser: s => s.auth.user, selectChatPanelOpen: () => false, selectChatPanelData: () => null }) };
  w.UBIFPlusSettings = { get: async () => ({employeeName:true,employeeFirstName:''}), subscribe() {} };
  for (const name of ['messages-page.js','employee.js']) w.eval(fs.readFileSync(`${__dirname}/../extension/${name}`, 'utf8'));
  await new Promise(resolve => w.setTimeout(resolve, 30));
  assert.equal(w.document.querySelector('[data-ubif-employee-name]').textContent, 'Jordan');
  assert.equal(w.UBIFPlusEmployee.firstName, 'Jordan');
  state.auth.user = { givenName: 'Sam', familyName: 'Reed' }; listener();
  await new Promise(resolve => w.setTimeout(resolve, 20));
  assert.equal(w.document.querySelector('[data-ubif-employee-name]').textContent, 'Sam');
  state.auth.user = null; listener();
  await new Promise(resolve => w.setTimeout(resolve, 20));
  assert.equal(w.document.querySelector('[data-ubif-employee-name]'), null);
});
