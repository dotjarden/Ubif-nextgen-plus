/* Copies the pinned darkreader devDependency into extension/vendor/.
   Run `npm run vendor` after changing its version in package.json.

   Dark Reader's embeddable build patches chrome.runtime.sendMessage and
   chrome.runtime.onMessage.addListener so it can route its own fetches. Every
   isolated-world content script shares one global, so that patch would also
   wrap support.js's messages to the service worker. The copy is therefore
   wrapped in a function whose `chrome` parameter is a private object: the
   engine patches that object instead and takes its non-extension path. Only
   chrome.dom is passed through, for reading closed shadow roots. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const target = path.join(root, 'extension', 'vendor', 'darkreader.js');

function build() {
  const dir = path.dirname(require.resolve('darkreader/package.json', { paths: [root] }));
  const { version } = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const source = fs.readFileSync(path.join(dir, 'darkreader.js'), 'utf8');
  const license = fs.readFileSync(path.join(dir, 'LICENSE'), 'utf8').trim();
  if (license.includes('*/')) throw new Error('Unexpected comment terminator in the Dark Reader license.');
  return [
    `/* Dark Reader ${version} (https://darkreader.org/), generated by scripts/vendor-darkreader.cjs. Do not edit.`,
    '',
    license.split('\n').map(line => `   ${line}`.trimEnd()).join('\n'),
    '*/',
    '(function (chrome) {',
    source.trimEnd(),
    '}).call(globalThis, { dom: globalThis.chrome && globalThis.chrome.dom });',
    ''
  ].join('\n');
}

if (require.main === module) {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, build());
  console.log(`Wrote ${path.relative(root, target)}`);
}

module.exports = { build, target };
